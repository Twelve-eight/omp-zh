const fs = require('fs');
const { spawnSync } = require('child_process');
const { parseExe, readModules, rebuild } = require('./rebuild.js');
const SRC = './work/omp-dl-18104.exe';
const buf = fs.readFileSync(SRC);
const { bun } = parseExe(buf);
const ds = bun.rawPtr + 8;
const hdr = Number(BigInt(buf.readUInt32LE(bun.rawPtr)) | (BigInt(buf.readUInt32LE(bun.rawPtr + 4)) << 32n));
const O = ds + hdr - 16 - 32;
const modOff = buf.readUInt32LE(O + 8), modLen = buf.readUInt32LE(O + 12);
const mods = readModules(buf, ds, modOff, modLen);
const bcOff = buf.readUInt32LE(ds + modOff + 24), bcLen = buf.readUInt32LE(ds + modOff + 28);
console.log('=== 18.10.4 基础结构扫描 ===');
console.log('文件大小 (size)         :', buf.length, 'bytes');
console.log('模块总数 (module count) :', mods.length);
console.log('modLen / 52             :', modLen / 52, '(rem: ' + (modLen % 52) + ')');
console.log('mod0 bytecode           : off=' + bcOff + ', len=' + bcLen);
const ci = mods.findIndex(m => m.name.toString('latin1').includes('CHANGELOG'));
console.log('CHANGELOG module index  :', ci, ci >= 0 ? '(' + mods[ci].name.toString('latin1') + ', len=' + mods[ci].contents.length + ')' : 'NOT FOUND');

console.log('=== 零改动 Roundtrip 验证 ===');
const rt = rebuild(buf, []);
fs.writeFileSync('./work/rt-18104.exe', rt);
const r1 = spawnSync('./work/rt-18104.exe', ['--version'], { encoding: 'utf8', timeout: 60000 });
console.log('roundtrip status        :', r1.status, 'out:', JSON.stringify((r1.stdout || '').trim()), 'err:', JSON.stringify((r1.stderr || '').trim()));

console.log('=== mode C 4KB 源码增长测试 ===');
const big = Buffer.concat([mods[0].contents.slice(0, -1), Buffer.from('/* ' + 'X'.repeat(4096) + ' */')]);
const rt2 = rebuild(buf, [big]);
fs.writeFileSync('./work/rt-grow-18104.exe', rt2);
const r2 = spawnSync('./work/rt-grow-18104.exe', ['--version'], { encoding: 'utf8', timeout: 60000 });
console.log('growth+4KB status       :', r2.status, 'out:', JSON.stringify((r2.stdout || '').trim()), 'err:', JSON.stringify((r2.stderr || '').trim()));
